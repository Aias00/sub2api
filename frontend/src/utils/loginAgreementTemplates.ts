export function renderLoginAgreementDocumentContent(
  markdown: string,
  options: RenderLoginAgreementDocumentOptions = {},
): string {
  const documentId = options.documentId?.trim() || "";
  const agreementDate = normalizeAgreementDate(options.updatedAt);
  const siteUrl = normalizeSiteUrlForDocument(options.frontendUrl);
  const contactInfo = normalizeContact(options.contactInfo);

  let content = markdown.trim();
  if (!content) {
    return "";
  }

  content = content
    .split(EFFECTIVE_DATE_PLACEHOLDER).join(agreementDate)
    .split(UPDATED_DATE_PLACEHOLDER).join(agreementDate)
    .split(SITE_URL_PLACEHOLDER).join(siteUrl)
    .split(CONTACT_INFO_PLACEHOLDER).join(contactInfo)
    .split("${contactInfo}").join(contactInfo);

  content = content.replace(
    /^\*\*生效日期：\*\*.*$/m,
    `**生效日期：** ${agreementDate}`,
  );
  content = content.replace(
    /^\*\*最后更新：\*\*.*$/m,
    `**最后更新：** ${agreementDate}`,
  );

  if (documentId === "terms") {
    content = content.replace(
      /当前站点地址：.*$/m,
      `当前站点地址：${siteUrl}`,
    );
    content = content.replace(
      /^- 联系方式：.*$/m,
      `- 联系方式：${contactInfo}`,
    );
  }

  if (documentId === "usage-policy") {
    content = content.replace(
      /如果您认为账号被误判、需要说明业务用途或提交整改材料，请联系：.*$/m,
      `如果您认为账号被误判、需要说明业务用途或提交整改材料，请联系：${contactInfo}`,
    );
  }

  if (documentId === "supported-regions") {
    content = content.replace(
      /如果您需要确认某个国家、地区或业务类型是否可以接入，请联系：.*$/m,
      `如果您需要确认某个国家、地区或业务类型是否可以接入，请联系：${contactInfo}`,
    );
  }

  if (documentId === "service-specific-terms") {
    content = content.replace(
      /- 如您需要企业协议、定制账期、发票、白名单、专属支持或其他商业安排，请联系：.*$/m,
      `- 如您需要企业协议、定制账期、发票、白名单、专属支持或其他商业安排，请联系：${contactInfo}`,
    );
  }

  return content;
}

export function isLegacyBlankLoginAgreementDocuments(
  docs?: LoginAgreementDocument[] | null,
): boolean {
  if (!Array.isArray(docs) || docs.length === 0) {
    return true;
  }
  if (docs.length !== legacyBlankDocuments.length) {
    return false;
  }
  return docs.every((doc, index) => {
    const legacy = legacyBlankDocuments[index];
    const id = doc.id?.trim() || "";
    const title = doc.title?.trim() || "";
    const content = doc.content_md?.trim() || "";
    return (
      content === "" &&
      (id === "" || id === legacy.id) &&
      (title === "" || title === legacy.title)
    );
  });
}
